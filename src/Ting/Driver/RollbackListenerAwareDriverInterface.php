namespace CCMBenchmark\Ting\Driver;

/**
 * A driver telling who asks when its transaction ends without being committed (the Mysqli and Pgsql drivers).
 *
 * The unit of work registers each entity it inserts in a transaction: when the transaction is rolled back, it stops
 * managing them, and their next save inserts them again although they still hold the id generated by the INSERT
 * rolled back. With a driver not implementing this interface, nothing is registered: such an entity stays managed, as
 * if its row existed: saved again unchanged, it writes nothing, and its changes are written by an UPDATE matching no
 * row. Detach it and set its id back to null to insert it again.
 */
interface RollbackListenerAwareDriverInterface
{
    /**
     * Registers $subject with the transaction open on this connection: $listener->rolledBack($subject) is called when
     * the transaction ends without being committed (see RollbackListenerInterface), and never once it is committed.
     * The subject is held weakly: a subject freed meanwhile is not notified.
     *
     * @return bool false when no transaction is open: nothing is registered
     */
    public function addRollbackListener(RollbackListenerInterface $listener, object $subject): bool;
}
